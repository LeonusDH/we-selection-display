package dev.selviz.geometry;

/**
 * Что именно рисует линия. Рендерер сам решает, каким блоком/цветом её показать.
 */
public enum LineStyle {
    /** Рамка вокруг блока первой точки (pos1, ЛКМ топором). */
    PRIMARY,
    /** Рамка вокруг блока второй точки (pos2, ПКМ топором). */
    SECONDARY,
    /** Рёбра кубоида. */
    CUBOID,
    /** Многоугольник //sel poly. */
    POLYGON,
    /** Цилиндр //sel cyl. */
    CYLINDER,
    /** Эллипсоид/сфера //sel ellipsoid, //sel sphere. */
    ELLIPSOID,
    /** Выпуклый многогранник //sel convex. */
    CONVEX,
    /** Любой другой тип выделения: рисуется его ограничивающий параллелепипед. */
    OTHER
}
